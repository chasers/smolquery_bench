    body                      Nullable(String),
    trace_id                  Nullable(String),
    span_id                   Nullable(String),
    trace_flags               Nullable(Int64),
    dropped_attributes_count  Nullable(Int64),
    service_name              Nullable(String),
    service_namespace         Nullable(String),
    service_version           Nullable(String),
    service_instance_id       Nullable(String),
    deployment_environment    Nullable(String),
    cloud_provider            Nullable(String),
    cloud_region              Nullable(String),
    cloud_availability_zone   Nullable(String),
    cloud_account_id          Nullable(String),
    k8s_cluster_name          Nullable(String),
    k8s_namespace_name        Nullable(String),
    k8s_deployment_name       Nullable(String),
